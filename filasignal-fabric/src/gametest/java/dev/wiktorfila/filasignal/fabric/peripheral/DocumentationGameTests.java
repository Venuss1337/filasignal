package dev.wiktorfila.filasignal.fabric.peripheral;

import com.google.gson.GsonBuilder;
import com.google.gson.JsonArray;
import com.google.gson.JsonObject;
import dev.wiktorfila.filasignal.core.analysis.Resolver;
import dev.wiktorfila.filasignal.core.host.HostRegistry;
import dev.wiktorfila.filasignal.core.parser.Parser;
import dev.wiktorfila.filasignal.core.source.SourceText;
import dev.wiktorfila.filasignal.fabric.computer.ComputerBlocks;
import dev.wiktorfila.filasignal.fabric.device.DeviceNetwork.Capability;
import dev.wiktorfila.filasignal.fabric.device.DeviceNetwork.Kind;
import net.fabricmc.fabric.api.gametest.v1.GameTest;
import net.minecraft.core.BlockPos;
import net.minecraft.gametest.framework.GameTestHelper;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Locale;
import java.util.Map;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * Keeps the documentation site honest. The Minecraft API reference is generated from the host registries that
 * programs actually run with, and every FilaScript block in the Minecraft guides must resolve against the registry
 * of the device it is written for.
 *
 * <p>Set {@code FILASIGNAL_UPDATE_DOCS=1} to rewrite {@code web/src/data/generated/minecraft-api.json}. Without it,
 * a stale file fails the test.
 */
public final class DocumentationGameTests {
    private static final Pattern FENCE = Pattern.compile("(?m)^([ \\t]*)```fsig([^\\n]*)\\n(.*?)^[ \\t]*```[ \\t]*$", Pattern.DOTALL);
    private static final Pattern OPTION = Pattern.compile("(\\w+)=\"([^\"]*)\"");

    @GameTest(maxTicks = 40)
    public void apiReferenceMatchesTheRegistriesAndGuidesResolve(GameTestHelper test) {
        var relative = new BlockPos(1, 1, 1);
        test.setBlock(relative, ComputerBlocks.block());
        var runtime = PeripheralLifecycle.runtime(test.getLevel().getServer());
        test.startSequence().thenWaitUntil(() -> {
            try {
                runtime.requireDevice(test.getLevel(), test.absolutePos(relative));
            } catch (IllegalArgumentException pending) {
                throw test.assertionException("The computer has not activated yet");
            }
        }).thenExecute(() -> {
            var computer = runtime.requireDevice(test.getLevel(), test.absolutePos(relative));
            var registries = new LinkedHashMap<String, HostRegistry>();
            registries.put("computer", DeviceHosts.registry(runtime, computer.id()));
            for (String kind : PeripheralLifecycle.programmableKinds()) {
                registries.put(kind, PeripheralLifecycle.driveHosts(test.getLevel().getServer(), kind));
            }
            // The documentation promises Direction constants wherever a face is chosen.
            registries.forEach((name, registry) -> {
                var all = new ArrayList<>(registry.functions());
                registry.objects().forEach(type -> all.addAll(type.methods().values()));
                for (var function : all) {
                    for (var slot : function.parameters()) {
                        test.assertTrue(!slot.name().equals("face") || slot.types().contains(HostRegistry.Type.ENUM),
                                name + ": " + function.name() + " does not accept Direction constants");
                    }
                }
            });
            Path root = HardwareGameTests.examples(test).getParent();
            try {
                reference(test, root, registries);
                guides(test, root, registries);
            } catch (IOException error) {
                throw test.assertionException(error.getMessage());
            }
        }).thenSucceed();
    }

    private static void reference(GameTestHelper test, Path root, Map<String, HostRegistry> registries) throws IOException {
        var document = new JsonObject();
        document.addProperty("note", "Generated by DocumentationGameTests from the mod's host registries. Do not edit.");
        var programs = new JsonObject();
        registries.forEach((name, registry) -> programs.add(name, registry(registry, name.equals("computer"))));
        document.add("programs", programs);
        var builtins = new JsonArray();
        Resolver.builtinEvents().forEach(event -> builtins.add(event(event)));
        document.add("builtinEvents", builtins);
        var kinds = new JsonArray();
        for (Kind kind : Kind.values()) {
            var entry = new JsonObject();
            entry.addProperty("id", kind.id());
            entry.addProperty("title", HardwareHosts.title(kind));
            var naming = HardwareHosts.NAMING.get(kind);
            entry.addProperty("type", naming == null ? null : naming.type());
            entry.addProperty("reference", naming == null ? null : naming.reference());
            var capabilities = new JsonArray();
            kind.capabilities().stream().sorted().forEach(capability -> capabilities.add(capability.name().toLowerCase(Locale.ROOT)));
            entry.add("capabilities", capabilities);
            entry.addProperty("programmable", kind.has(Capability.EXECUTION) && kind != Kind.COMPUTER);
            var events = new JsonArray();
            HardwareEvents.remote(kind).forEach(definition -> events.add(event(definition.event(definition.name()))));
            entry.add("events", events);
            var own = new JsonArray();
            HardwareEvents.hardware(kind).forEach(definition -> own.add(definition.name()));
            entry.add("ownEvents", own);
            entry.add("localCapabilities", strings(entry.get("programmable").getAsBoolean()
                    ? LocalHosts.capabilities(kind) : java.util.Set.of()));
            kinds.add(entry);
        }
        document.add("kinds", kinds);
        document.add("computerCapabilities", strings(DeviceHosts.CAPABILITIES));
        String generated = new GsonBuilder().setPrettyPrinting().disableHtmlEscaping().serializeNulls().create()
                .toJson(document) + "\n";
        Path file = root.resolve("web/src/data/generated/minecraft-api.json");
        if ("1".equals(System.getenv("FILASIGNAL_UPDATE_DOCS"))) {
            Files.createDirectories(file.getParent());
            Files.writeString(file, generated, StandardCharsets.UTF_8);
            return;
        }
        String current = Files.exists(file) ? Files.readString(file, StandardCharsets.UTF_8).replace("\r\n", "\n") : "";
        test.assertTrue(current.equals(generated), "web/src/data/generated/minecraft-api.json is stale. "
                + "Run the GameTests with FILASIGNAL_UPDATE_DOCS=1 and commit the result.");
    }

    /**
     * A program's API. Device programs refer to other devices only for their events, which {@code kinds} lists, so
     * their object types are included only when they have methods, such as a Storage Server's storage.
     */
    private static JsonObject registry(HostRegistry registry, boolean computer) {
        var result = new JsonObject();
        var functions = new JsonArray();
        registry.functions().forEach(function -> functions.add(function(function)));
        result.add("functions", functions);
        var objects = new JsonArray();
        for (var type : registry.objects()) {
            if (!computer && type.methods().isEmpty()) {
                continue;
            }
            var object = new JsonObject();
            object.addProperty("name", type.name());
            var properties = new JsonArray();
            type.properties().values().stream().sorted(Comparator.comparing(HostRegistry.Function::name))
                    .forEach(property -> properties.add(function(property)));
            object.add("properties", properties);
            var methods = new JsonArray();
            type.methods().values().stream().sorted(Comparator.comparing(HostRegistry.Function::name))
                    .forEach(method -> methods.add(function(method)));
            object.add("methods", methods);
            var events = new JsonArray();
            type.events().values().stream().sorted(Comparator.comparing(HostRegistry.Event::name))
                    .forEach(event -> events.add(event(event)));
            object.add("events", events);
            objects.add(object);
        }
        result.add("objects", objects);
        var events = new JsonArray();
        registry.events().forEach(event -> events.add(event(event)));
        result.add("events", events);
        var enums = new JsonObject();
        registry.enums().entrySet().stream().sorted(Map.Entry.comparingByKey())
                .forEach(entry -> enums.add(entry.getKey(), strings(entry.getValue())));
        result.add("enums", enums);
        return result;
    }

    private static JsonObject function(HostRegistry.Function function) {
        var result = new JsonObject();
        result.addProperty("name", function.name());
        result.add("parameters", slots(function.parameters()));
        result.add("returns", slots(function.returns()));
        result.addProperty("valueOrError", function.valueOrError());
        result.addProperty("documentation", function.documentation());
        result.add("capabilities", strings(function.capabilities()));
        result.addProperty("cost", function.cost());
        result.add("errors", strings(function.errors()));
        result.add("examples", strings(function.examples()));
        result.addProperty("reference", function.reference());
        return result;
    }

    private static JsonArray slots(List<HostRegistry.Slot> slots) {
        var result = new JsonArray();
        for (var slot : slots) {
            var entry = new JsonObject();
            entry.addProperty("name", slot.name());
            entry.add("types", strings(slot.types().stream().map(type -> type.name().toLowerCase(Locale.ROOT)).sorted().toList()));
            entry.addProperty("handleType", slot.handleType());
            result.add(entry);
        }
        return result;
    }

    private static JsonObject event(HostRegistry.Event event) {
        var result = new JsonObject();
        result.addProperty("name", event.name());
        result.add("filters", slots(event.filters()));
        result.add("parameters", strings(event.parameters()));
        result.addProperty("documentation", event.documentation());
        return result;
    }

    /** A sorted array for sets, or the given order for lists. */
    private static JsonArray strings(java.util.Collection<String> values) {
        var result = new JsonArray();
        (values instanceof List<String> list ? list : values.stream().sorted().toList()).forEach(result::add);
        return result;
    }

    /**
     * Resolves every {@code fsig} block in the Minecraft guides. A block runs on the computer unless it names a
     * device kind with {@code target="entity_detector"}. {@code check="none"} marks a fragment that is not a whole
     * program, such as a single handler shown on its own.
     */
    private static void guides(GameTestHelper test, Path root, Map<String, HostRegistry> registries) throws IOException {
        Path docs = root.resolve("web/src/content/docs/minecraft");
        var problems = new ArrayList<String>();
        int checked = 0;
        List<Path> pages;
        try (var files = Files.walk(docs)) {
            pages = files.filter(path -> path.toString().endsWith(".md") || path.toString().endsWith(".mdx")).sorted().toList();
        }
        for (Path page : pages) {
            String text = Files.readString(page, StandardCharsets.UTF_8).replace("\r\n", "\n");
            Matcher fence = FENCE.matcher(text);
            while (fence.find()) {
                var options = new LinkedHashMap<String, String>();
                Matcher option = OPTION.matcher(fence.group(2));
                while (option.find()) {
                    options.put(option.group(1), option.group(2));
                }
                if (options.getOrDefault("check", "").equals("none")) {
                    continue;
                }
                String target = options.getOrDefault("target", "computer");
                HostRegistry registry = registries.get(target);
                String where = docs.relativize(page) + " line " + (text.substring(0, fence.start()).split("\n", -1).length);
                if (registry == null) {
                    problems.add(where + ": unknown target " + target);
                    continue;
                }
                String source = fence.group(3).replaceAll("(?m)^" + Pattern.quote(fence.group(1)), "");
                var resolved = Resolver.resolve(Parser.parse(new SourceText(where, "guide.fsig", source)), registry);
                checked++;
                if (!resolved.diagnostics().isEmpty()) {
                    var first = resolved.diagnostics().getFirst();
                    problems.add(where + " (" + target + "): " + first.message() + " at " + first.span().start());
                }
            }
        }
        test.assertTrue(problems.isEmpty(), "Guide examples do not resolve:\n" + String.join("\n", problems));
        test.assertTrue(checked > 0, "No guide examples were found under " + docs);
    }
}
